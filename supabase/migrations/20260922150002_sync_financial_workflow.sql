-- ============================================================================
-- Keep financial milestones and their operational workflows in lockstep.
--
-- Opname is entered in the Finance tab, but it is also the terminal milestone
-- of Desain Siteplan. Likewise, an approved invoice is the terminal event of
-- the routing document. These trigger-only functions make the relationship
-- hold regardless of which screen a user edits from.
-- ============================================================================

create or replace function public.sync_siteplan_opname_from_spk()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_design       public.designs%rowtype;
  v_current      public.design_revisions%rowtype;
  v_finish       public.design_revisions%rowtype;
  v_activity_id  uuid;
  v_marker       constant text := 'Disinkronkan dari Keuangan: Opname.';
begin
  select d.*
  into v_design
  from public.designs d
  where d.spk_id = new.id
    and d.phase = 'siteplan'
    and d.status = 'Active'
  order by d.created_at desc
  limit 1;

  if not found then
    return new;
  end if;

  select dr.*
  into v_current
  from public.design_revisions dr
  where dr.design_id = v_design.id
    and dr.status = 'Active'
  order by dr.revision_no desc, dr.created_at desc
  limit 1;

  if new.opname_marked_at is not null
     and v_current.stage::text in ('Finish', 'Opname') then
    if v_current.stage::text = 'Finish' then
      update public.design_revisions
      set completed_at = coalesce(completed_at, new.opname_marked_at)
      where id = v_current.id;

      insert into public.design_revisions (
        design_id,
        revision_no,
        stage,
        started_at,
        completed_at,
        notes,
        created_by
      )
      values (
        v_design.id,
        v_current.revision_no,
        'Opname',
        new.opname_marked_at,
        new.opname_marked_at,
        v_marker,
        new.opname_marked_by
      )
      on conflict (design_id, revision_no, stage) do update
      set started_at = coalesce(public.design_revisions.started_at, excluded.started_at),
          completed_at = excluded.completed_at,
          notes = case
            when public.design_revisions.notes = v_marker then v_marker
            else public.design_revisions.notes
          end;
    else
      update public.design_revisions
      set started_at = coalesce(started_at, new.opname_marked_at),
          completed_at = new.opname_marked_at
      where id = v_current.id;
    end if;

    update public.designs
    set approved_at = coalesce(approved_at, new.opname_marked_at),
        approved_by = coalesce(approved_by, new.opname_marked_by)
    where id = v_design.id;

    select a.id
    into v_activity_id
    from public.spk_activities a
    where a.spk_id = new.id
      and a.name = 'Opname'
      and a.measurement = 'stage'
    limit 1;

    if v_activity_id is not null then
      insert into public.activity_progress (
        spk_activity_id,
        progress_date,
        stage,
        source,
        recorded_by,
        notes
      )
      values (
        v_activity_id,
        new.opname_marked_at::date,
        'Selesai',
        'manual',
        new.opname_marked_by,
        v_marker
      );
    end if;
  elsif new.opname_marked_at is null
        and old.opname_marked_at is not null
        and v_current.stage::text = 'Opname'
        and v_current.notes = v_marker then
    -- Undo only the stage generated by this financial mark. A manually
    -- completed design Opname remains intact when finance is corrected.
    delete from public.design_revisions where id = v_current.id;

    select dr.*
    into v_finish
    from public.design_revisions dr
    where dr.design_id = v_design.id
      and dr.revision_no = v_current.revision_no
      and dr.stage::text = 'Finish'
      and dr.status = 'Active'
    limit 1;

    if found then
      update public.design_revisions
      set completed_at = null
      where id = v_finish.id;
    end if;

    update public.designs
    set approved_at = null,
        approved_by = null
    where id = v_design.id;

    select a.id
    into v_activity_id
    from public.spk_activities a
    where a.spk_id = old.id
      and a.name = 'Opname'
      and a.measurement = 'stage'
    limit 1;

    if v_activity_id is not null then
      insert into public.activity_progress (
        spk_activity_id,
        progress_date,
        stage,
        source,
        recorded_by,
        notes
      )
      values (
        v_activity_id,
        current_date,
        'Belum Mulai',
        'manual',
        old.opname_marked_by,
        v_marker
      );
    end if;
  end if;

  return new;
end;
$fn$;

drop trigger if exists spks_sync_siteplan_opname on public.spks;
create trigger spks_sync_siteplan_opname
after update of opname_marked_at on public.spks
for each row execute function public.sync_siteplan_opname_from_spk();

create or replace function public.sync_routing_from_invoice()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_spk_id     uuid;
  v_invoice    public.invoices%rowtype;
  v_routing_id uuid;
  v_step       public.routing_history%rowtype;
  v_finished_at timestamptz;
begin
  v_spk_id := case when tg_op = 'DELETE' then old.spk_id else new.spk_id end;

  select i.*
  into v_invoice
  from public.invoices i
  where i.spk_id = v_spk_id
    and i.status = 'Approved'
  order by i.invoice_date desc nulls last, i.updated_at desc
  limit 1;

  select r.id
  into v_routing_id
  from public.spk_routing r
  where r.spk_id = v_spk_id
  order by r.created_at desc
  limit 1;

  if v_routing_id is null then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  select h.*
  into v_step
  from public.routing_history h
  where h.spk_routing_id = v_routing_id
    and h.step_name = 'Invoiced'
  limit 1;

  if not found then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  if v_invoice.id is not null then
    v_finished_at := coalesce(
      v_invoice.invoice_date::timestamp at time zone 'Asia/Bangkok',
      now()
    );
    -- Old imports can have a same-day start written after the invoice's
    -- calendar timestamp. Keep the financial date separately and never
    -- violate the routing history's completed_at >= started_at invariant.
    v_finished_at := greatest(v_finished_at, coalesce(v_step.started_at, v_finished_at));

    update public.routing_history
    set status = 'Completed',
        started_at = coalesce(started_at, v_finished_at),
        completed_at = v_finished_at,
        invoice_number = v_invoice.invoice_number,
        invoice_value = v_invoice.invoice_value,
        invoice_date = v_invoice.invoice_date
    where id = v_step.id;

    update public.spks
    set status = 'Selesai'
    where id = v_spk_id;
  elsif (tg_op = 'DELETE' and old.status = 'Approved')
        or (tg_op <> 'DELETE' and old.status = 'Approved' and new.status <> 'Approved') then
    -- Moving the last approved invoice back to a non-final state reopens the
    -- final routing stage and the project itself. Creating a Draft invoice
    -- never alters an independently completed legacy routing document.
    update public.routing_history
    set status = 'In Progress',
        completed_at = null
    where id = v_step.id
      and status = 'Completed';

    update public.spks
    set status = 'On Going'
    where id = v_spk_id;
  end if;

  return case when tg_op = 'DELETE' then old else new end;
end;
$fn$;

drop trigger if exists invoices_sync_routing on public.invoices;
create trigger invoices_sync_routing
after insert or update or delete on public.invoices
for each row execute function public.sync_routing_from_invoice();

-- Trigger functions are internal implementation details, never RPCs.
revoke all on function public.sync_siteplan_opname_from_spk() from public, anon, authenticated;
revoke all on function public.sync_routing_from_invoice() from public, anon, authenticated;

-- Reconcile the records that existed before the triggers. Assigning the
-- existing values intentionally fires the same audited, idempotent code path
-- used by future edits.
update public.spks
set opname_marked_at = opname_marked_at
where opname_marked_at is not null;

update public.invoices
set updated_at = updated_at
where status = 'Approved';
